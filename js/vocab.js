  function shuffle(a) {
    for (var i = a.length - 1; i > 0; i--) {
      var j = Math.floor(Math.random() * (i + 1)), t = a[i]; a[i] = a[j]; a[j] = t;
    }
    return a;
  }
  function pick(list, n) { return shuffle(list.slice(0)).slice(0, n); }

  function buildPractice(words, opts) {
    opts = opts || {};
    var all = VOCAB;
    var others = all.filter(function (v) {
      return words.every(function (w) { return w.w !== v.w; });
    });
    var qs = [];
    words.forEach(function (v, i) {
      var type = (i + (opts.offset || 0)) % 3;   // 0 = arti->kata, 1 = kata->arti, 2 = konteks
      if (type === 0) {
        var dis = pick(others, 3);
        qs.push({
          kind: "id2en", word: v.w,
          text: "Apa arti kata \"" + v.id + "\" dalam bahasa Inggris?",
          options: shuffle([v.w].concat(dis.map(function (d) { return d.w; }))),
          answer: v.w,
          explain: v.w + " = " + v.id + (v.ex ? "  •  \"" + v.ex + "\"" : "")
        });
      } else if (type === 1) {
        var dis2 = pick(others, 3);
        qs.push({
          kind: "en2id", word: v.w,
          text: "Apa arti kata \"" + v.w + "\"?",
          options: shuffle([v.id].concat(dis2.map(function (d) { return d.id; }))),
          answer: v.id,
          explain: v.w + " (" + v.pos + ") = " + v.id + (v.exId ? "  •  " + v.exId : "")
        });
      } else {
        var ctx = v.ex || "";
        var blanked = ctx.replace(new RegExp("\\b" + v.w.replace(/[.*+?^${}()|[\]\\]/g, "\\$&") + "\\b", "i"), "______");
        var same = others.filter(function (d) {
          return Math.abs(d.w.length - v.w.length) <= 4 && d.pos === v.pos;
        });
        var pool = same.length >= 3 ? same : others;
        var dis3 = pick(pool, 3);
        qs.push({
          kind: "ctx", word: v.w,
          text: "Lengkapi kalimat: \"" + blanked + "\"",
          options: shuffle([v.w].concat(dis3.map(function (d) { return d.w; }))),
          answer: v.w,
          explain: v.w + " = " + v.id + (v.exId ? "  •  " + v.exId : "")
        });
      }
    });
    return qs;
  }

  /* ---------- kamus cepat: API gratis (tanpa key) ---------- */
  function lookupWord(word) {
    var w = String(word || "").trim().toLowerCase();
    if (!w) return Promise.reject(new Error("kata kosong"));
    var out = { word: w, local: null, def: "", phonetic: "", pos: "", examples: [], synonyms: [], antonyms: [], id: "", source: "" };
    var local = VOCAB.filter(function (v) { return v.w.toLowerCase() === w; })[0];
    if (local) {
      out.local = local;
      out.id = local.id;
      out.def = local.id;
      out.phonetic = local.ipa;
      out.pos = local.pos;
      out.examples = [local.ex];
      out.synonyms = local.syn || [];
      out.antonyms = local.ant || [];
      out.source = "bank kosakata";
    }
    var tasks = [];
    tasks.push(fetch("https://api.dictionaryapi.dev/api/v2/entries/en/" + encodeURIComponent(w))
      .then(function (r) { return r.ok ? r.json() : []; })
      .then(function (data) {
        if (!data || !data.length) return;
        var e = data[0];
        out.word = e.word || out.word;
        var ph = e.phonetic || (e.phonetics && e.phonetics.length ? e.phonetics[0].text : "");
        if (ph) out.phonetic = ph;
        var m = e.meanings && e.meanings[0];
        if (m) {
          out.pos = m.partOfSpeech || out.pos;
          if (m.definitions && m.definitions[0]) out.def = m.definitions[0].definition || out.def;
          (m.definitions || []).forEach(function (d) { if (d.example && out.examples.length < 4) out.examples.push(d.example); });
          out.synonyms = (m.synonyms || []).slice(0, 8);
          out.antonyms = (m.antonyms || []).slice(0, 6);
        }
        out.source = out.source ? out.source + " + dictionaryapi.dev" : "dictionaryapi.dev";
      }).catch(function () { /* offline → pakai bank lokal */ }));
    if (!local) {
      tasks.push(fetch("https://api.mymemory.translated.net/get?q=" + encodeURIComponent(w) + "&langpair=en%7Cid")
        .then(function (r) { return r.ok ? r.json() : null; })
        .then(function (j) {
          if (j && j.responseData && j.responseData.translatedText && j.responseData.match > 0.4) {
            out.id = j.responseData.translatedText;
            if (!out.def) out.def = j.responseData.translatedText;
          }
        }).catch(function () { }));
    }
    return Promise.all(tasks).then(function () { return out; });
  }

